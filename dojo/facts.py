"""Compute docs/dataset_facts.md from the seeded template.

Lesson prose cites concrete numbers; this file keeps those citations honest.
Regenerated by every `dojo seed`.
"""
from __future__ import annotations

from datetime import datetime, timezone

from dojo import db
from dojo.config import ROOT, load_config

TABLES = ["customers", "products", "orders", "order_items", "reviews", "events", "staff"]


def write_facts() -> None:
    cfg = load_config()
    lines: list[str] = []
    out = lines.append

    with db.connect(cfg.template_db) as conn:
        def one(q, *params):
            return conn.execute(q, params or None).fetchone()

        def all_(q, *params):
            return conn.execute(q, params or None).fetchall()

        out("# Dataset facts")
        out("")
        out(f"Generated by `dojo seed` on {datetime.now(timezone.utc):%Y-%m-%d %H:%M} UTC "
            f"against `{cfg.template_db}`. Do not edit by hand.")
        out("")
        out("## Row counts")
        out("")
        out("| table | rows |")
        out("|---|---:|")
        for t in TABLES:
            (n,) = one(f"SELECT count(*) FROM {t}")
            out(f"| {t} | {n:,} |")
        out("")

        out("## Orders")
        out("")
        out("| status | orders |")
        out("|---|---:|")
        for status, n in all_("SELECT status, count(*) FROM orders GROUP BY status ORDER BY status"):
            out(f"| {status} | {n:,} |")
        lo, hi = one("SELECT min(created_at), max(created_at) FROM orders")
        out("")
        out(f"- `created_at` spans **{lo:%Y-%m-%d}** to **{hi:%Y-%m-%d}**.")
        lo_t, hi_t, avg_t = one("SELECT min(total), max(total), round(avg(total),2) FROM orders")
        out(f"- `total` ranges {lo_t} .. {hi_t}, average {avg_t}.")
        row = one("SELECT count(*), coalesce(sum(total),0) FROM orders WHERE customer_id = 4242")
        out(f"- Customer **4242** has **{row[0]}** orders totalling **{row[1]}**.")
        (n,) = one("SELECT count(*) FROM customers c WHERE NOT EXISTS (SELECT 1 FROM orders o WHERE o.customer_id = c.id)")
        out(f"- Customers with **zero orders**: **{n:,}**.")
        out("")

        out("## Customers")
        out("")
        (n,) = one("SELECT count(DISTINCT country) FROM customers")
        out(f"- {n} distinct countries. Top 5:")
        out("")
        out("| country | customers |")
        out("|---|---:|")
        for c, cnt in all_("SELECT country, count(*) FROM customers GROUP BY country ORDER BY count(*) DESC, country LIMIT 5"):
            out(f"| {c} | {cnt:,} |")
        lo, hi = one("SELECT min(created_at), max(created_at) FROM customers")
        out("")
        out(f"- `created_at` spans {lo:%Y-%m-%d} to {hi:%Y-%m-%d}.")
        out("")

        out("## Products")
        out("")
        out("| category | products | avg price |")
        out("|---|---:|---:|")
        for cat, cnt, avg in all_("SELECT category, count(*), round(avg(price),2) FROM products GROUP BY category ORDER BY category"):
            out(f"| {cat} | {cnt:,} | {avg} |")
        lo_p, hi_p = one("SELECT min(price), max(price) FROM products")
        out("")
        out(f"- `price` ranges {lo_p} .. {hi_p}.")
        (n,) = one("SELECT count(*) FROM products p WHERE NOT EXISTS (SELECT 1 FROM order_items oi WHERE oi.product_id = p.id)")
        out(f"- Products never ordered: **{n:,}**.")
        out("")

        out("## Reviews")
        out("")
        (avg,) = one("SELECT round(avg(rating),2) FROM reviews")
        out(f"- Average rating: **{avg}**.")
        out("| rating | reviews |")
        out("|---|---:|")
        for r, cnt in all_("SELECT rating, count(*) FROM reviews GROUP BY rating ORDER BY rating"):
            out(f"| {r} | {cnt:,} |")
        out("")

        out("## Events")
        out("")
        lo, hi = one("SELECT min(ts), max(ts) FROM events")
        out(f"- `ts` spans **{lo:%Y-%m-%d %H:%M}** to **{hi:%Y-%m-%d %H:%M}** (strictly increasing with `id`).")
        out("| event_type | events |")
        out("|---|---:|")
        for et, cnt in all_("SELECT event_type, count(*) FROM events GROUP BY event_type ORDER BY count(*) DESC"):
            out(f"| {et} | {cnt:,} |")
        out("")

        out("## Staff")
        out("")
        (n,) = one("SELECT count(*) FROM staff")
        (ceo,) = one("SELECT name FROM staff WHERE manager_id IS NULL")
        (depth,) = one(
            """
            WITH RECURSIVE t AS (
              SELECT id, 1 AS depth FROM staff WHERE manager_id IS NULL
              UNION ALL
              SELECT s.id, t.depth + 1 FROM staff s JOIN t ON s.manager_id = t.id
            ) SELECT max(depth) FROM t
            """
        )
        out(f"- {n} staff; CEO (the only NULL `manager_id`) is **{ceo}**; org tree is **{depth}** levels deep.")
        out("| department | staff | avg salary |")
        out("|---|---:|---:|")
        for d, cnt, avg in all_("SELECT department, count(*), round(avg(salary)) FROM staff GROUP BY department ORDER BY department"):
            out(f"| {d} | {cnt} | {avg} |")
        out("")

    path = ROOT / "docs" / "dataset_facts.md"
    path.parent.mkdir(exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")
    print(f"  wrote {path.relative_to(ROOT)}")
