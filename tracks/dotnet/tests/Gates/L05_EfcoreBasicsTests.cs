    [Fact]
    public async Task Ex1_ListingProductsProjectsAndSorts()
    {
        using var host = NewHost();
        using var client = host.CreateClient();

        var response = await client.GetAsync("/l05/products");
        await Teach.Status(HttpStatusCode.OK, response,
            "GET /l05/products must answer 200 - reread README ex1.");

        Teach.Equal("2,4,5,1,3", await Ids(response),
            "Every product, name ascending: Bokken, Gi, Obi, Tatami mat, Zabuton. Getting "
                + "1,2,3,4,5 means you never ordered - the order rows come back in is not a "
                + "promise the database makes.");

        string raw = await client.GetStringAsync("/l05/products");
        Teach.True(!raw.Contains("category", StringComparison.OrdinalIgnoreCase),
            "The list is meant to be a ProductSummary - id, name and price only. \"category\" "
                + "in the body means you returned whole Product entities, which sends columns "
                + "nobody asked for over the wire. Project with Select before ToListAsync.\n"
                + "  body: " + raw);
    }

    [Fact]
    public async Task Ex2_OneProductOrA404()
