    }

    [Fact]
    public async Task Ex3_CreateAndDeleteReallyChangeTheDatabase()
    {
        using var host = NewHost();
        using var client = host.CreateClient();

        var created = await client.PostAsJsonAsync("/l05/products",
            new { name = "Shinai", priceCents = 4500, category = "training" });
        await Teach.Status(HttpStatusCode.Created, created,
            "A successful POST is 201 Created - reread README ex3.");
        Teach.Equal("/l05/products/6", created.Headers.Location?.ToString(),
            "The Location header points at the new row. Five products are seeded, so the "
                + "database gives the new one id 6 - and you only know that after "
                + "SaveChangesAsync, because the id is generated by the database.");

        var fetched = await client.GetAsync("/l05/products/6");
        await Teach.Status(HttpStatusCode.OK, fetched,
            "The new product has to still be there on the next request. A 404 means you "
                + "called Add but never SaveChangesAsync - nothing left the change tracker.");
        Teach.Equal(6, host.Query(db => db.Products.Count()),
            "The table should hold six rows now.");

        var blank = await client.PostAsJsonAsync("/l05/products",
            new { name = "  ", priceCents = 4500, category = "training" });
        await Teach.Status(HttpStatusCode.BadRequest, blank,
            "A blank name is a 400, and nothing should be written.");

        var free = await client.PostAsJsonAsync("/l05/products",
            new { name = "Freebie", priceCents = 0, category = "training" });
        await Teach.Status(HttpStatusCode.BadRequest, free,
            "priceCents has to be positive.");
        Teach.Equal(6, host.Query(db => db.Products.Count()),
            "Two rejected requests must not have inserted anything. Validate before Add.");

        var deleted = await client.DeleteAsync("/l05/products/5");
        await Teach.Status(HttpStatusCode.NoContent, deleted,
            "A successful DELETE has nothing to say: 204.");
        Teach.Equal(5, host.Query(db => db.Products.Count()),
            "The row should be gone from the table, not just from the response.");

        var gone = await client.GetAsync("/l05/products/5");
        await Teach.Status(HttpStatusCode.NotFound, gone, "…so fetching it is now a 404.");

        var again = await client.DeleteAsync("/l05/products/5");
        await Teach.Status(HttpStatusCode.NotFound, again,
            "Deleting something that is not there is a 404: you cannot remove an entity you "
                + "did not load.");
    }

    [Fact]
    public async Task Ex4_TrackingIsWhatMakesASaveWorkAtAll()
    {
        using var host = NewHost();
        using var client = host.CreateClient();

        var untracked = await client.PostAsync("/l05/products/3/rename?name=Cushion&tracked=false", null);
        await Teach.Status(HttpStatusCode.OK, untracked,
            "POST /l05/products/3/rename?name=Cushion&tracked=false must answer 200 - "
                + "reread README ex4.");

        var untrackedBody = await untracked.Content.ReadFromJsonAsync<RenameDto>();
        Teach.Equal("Cushion", untrackedBody?.Name,
            "The object in memory really was renamed - assigning to a property always works.");
        Teach.Equal(0, untrackedBody?.Changes,
            "SaveChangesAsync returned something other than 0 for an AsNoTracking query. "
                + "An untracked entity is not in the change tracker, so EF has no idea it "
                + "changed and writes nothing.");
        Teach.Equal("Zabuton", host.Query(db => db.Products.Single(p => p.Id == 3).Name),
            "…and the database still says Zabuton. This is the AsNoTracking trap: no "
                + "exception, no warning, no update.");

        var tracked = await client.PostAsync("/l05/products/2/rename?name=Shinai&tracked=true", null);
        var trackedBody = await tracked.Content.ReadFromJsonAsync<RenameDto>();
        Teach.Equal(1, trackedBody?.Changes,
            "A tracked entity that you changed produces exactly one write, and "
                + "SaveChangesAsync returns the number of rows it touched. You do not call "
                + "Update - the change tracker already noticed.");
        Teach.Equal("Shinai", host.Query(db => db.Products.Single(p => p.Id == 2).Name),
            "…and this time the row really changed.");

        var missing = await client.PostAsync("/l05/products/99/rename?name=Nope&tracked=true", null);
        await Teach.Status(HttpStatusCode.NotFound, missing,
            "Renaming a product that does not exist is a 404.");
    }

    [Fact]
    public async Task Challenge_APageAndItsTotal()
    {
        using var host = NewHost();
        using var client = host.CreateClient();

        var second = await client.GetAsync("/l05/products/page?page=2&size=2");
        await Teach.Status(HttpStatusCode.OK, second,
            "GET /l05/products/page?page=2&size=2 must answer 200 - reread README challenge.");

        var page = await second.Content.ReadFromJsonAsync<PageDto>();
        Teach.Equal("5,1", string.Join(",", (page?.Items ?? []).Select(i => i.Id)),
            "By name the order is Bokken, Gi, Obi, Tatami mat, Zabuton; page 2 of size 2 is "
                + "the third and fourth of those - Obi and Tatami mat. Skip before Take, and "
                + "order before both.");
        Teach.Equal(5, page?.Total,
            "total is how many rows exist, not how many you returned - that is what lets a "
                + "client draw the page numbers.");
        Teach.Equal(2, page?.Page, "Echo back the page you served.");
        Teach.Equal(2, page?.Size, "…and the size.");

        var defaults = await client.GetFromJsonAsync<PageDto>("/l05/products/page");
        Teach.Equal("2,4", string.Join(",", (defaults?.Items ?? []).Select(i => i.Id)),
            "With no query string at all, page defaults to 1 and size to 2.");

        var zero = await client.GetAsync("/l05/products/page?page=0");
        await Teach.Status(HttpStatusCode.BadRequest, zero,
            "Pages are 1-based, so page=0 is a 400.");

        var huge = await client.GetAsync("/l05/products/page?size=51");
        await Teach.Status(HttpStatusCode.BadRequest, huge,
            "An unbounded page size is how one client takes the database down. Cap it at 50 "
                + "and reject anything larger.");
    }

    [Fact]
    public async Task Review1_TheCheapestFew()
    {
        using var host = NewHost();
        using var client = host.CreateClient();

        var response = await client.GetAsync("/l05/review/products/cheapest");
        await Teach.Status(HttpStatusCode.OK, response,
            "GET /l05/review/products/cheapest must answer 200 - reread README review.");
        Teach.Equal("5,3,2", await Ids(response),
            "Cheapest three: Obi 2400, Zabuton 3400, Bokken 5900. The default limit is 3.");

        var one = await client.GetAsync("/l05/review/products/cheapest?limit=1");
        Teach.Equal("5", await Ids(one), "limit=1 gives just the cheapest.");

        var zero = await client.GetAsync("/l05/review/products/cheapest?limit=0");
        await Teach.Status(HttpStatusCode.BadRequest, zero,
            "Asking for zero rows is a malformed request, not an empty list: 400.");
    }

    private static SqliteHost<CatalogDb> NewHost() =>
        new SqliteHost<CatalogDb>().Seed(db => db.Products.AddRange(
            new Product { Id = 1, Name = "Tatami mat", PriceCents = 12500, Category = "equipment" },
            new Product { Id = 2, Name = "Bokken", PriceCents = 5900, Category = "training" },
            new Product { Id = 3, Name = "Zabuton", PriceCents = 3400, Category = "equipment" },
            new Product { Id = 4, Name = "Gi", PriceCents = 8900, Category = "clothing" },
            new Product { Id = 5, Name = "Obi", PriceCents = 2400, Category = "clothing" }));

    private static async Task<string> Ids(HttpResponseMessage response)
    {
        var items = await response.Content.ReadFromJsonAsync<List<SummaryDto>>();
        return string.Join(",", (items ?? []).Select(i => i.Id));
    }

    private sealed record SummaryDto(int Id, string? Name, int PriceCents);

    private sealed record ProductDto(int Id, string? Name, int PriceCents, string? Category);

    private sealed record RenameDto(int Changes, string? Name);

    private sealed record PageDto(List<SummaryDto>? Items, int Total, int Page, int Size);
}
