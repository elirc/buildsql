using Microsoft.EntityFrameworkCore;

namespace DotnetDojo.Api.D10_EfcoreCrud;

public class Ex3 : IEndpointMapper
{
    public void MapEndpoints(IEndpointRouteBuilder app)
    {
        app.MapPost("/d10/members", Create);
    }

    private static async Task<IResult> Create(D10Db db, NewMember request)
    {
        if (string.IsNullOrWhiteSpace(request.Name)
            || string.IsNullOrWhiteSpace(request.Email)
            || request.Credits < 0)
        {
            return TypedResults.BadRequest("name and email are required and credits cannot be negative.");
        }

        var member = new Member
        {
            Name = request.Name,
            Email = request.Email,
            Credits = request.Credits,
            Grade = "white",
        };

        db.Members.Add(member);

        // The id is generated by the database, so it only exists after this.
        await db.SaveChangesAsync();

        return TypedResults.Created($"/d10/members/{member.Id}", member);
    }
}
